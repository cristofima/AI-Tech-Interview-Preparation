// =========================================================================
// AI Tech Interview - Response Sync API Route
// POST: Persist a recorded answer (online or replayed from IndexedDB),
//       idempotently, together with its audio (persisted to PostgreSQL)
// GET: Get all responses for a session
// =========================================================================

import { NextRequest, NextResponse } from 'next/server';
import { prisma } from '@/lib/prisma';
import {
  parseSyncFormData,
  submitResponse,
  SubmissionError,
  type SubmissionResult,
  type TransactionRunner,
} from '@/lib/response-submission';
import type { ApiResponse } from '@/types/api';

/**
 * Multipart fields accepted by POST /api/responses/sync
 */
export interface SyncResponseRequest {
  questionId: string;
  sessionId: string;
  transcription?: string;
  durationSeconds: number;
  /** Idempotency key generated by the browser when the answer was recorded. */
  clientResponseId?: string;
  /** Unix ms when the recording finished; newer recordings win. */
  recordedAt?: number;
  /** Hex SHA-256 of the audio part; verified server-side. */
  audioSha256?: string;
  audioMimeType?: string;
  recordedOffline?: boolean;
}

export type SyncResponseResponse = SubmissionResult;

const runInTransaction: TransactionRunner = (fn) => prisma.$transaction(fn);

/**
 * POST /api/responses/sync
 *
 * Outcomes (see src/lib/response-submission.ts):
 *   201 created | 200 updated | 200 duplicate | 200 superseded
 * Errors:
 *   400 INVALID_REQUEST / AUDIO_CHECKSUM_MISMATCH, 404 SESSION_NOT_FOUND /
 *   QUESTION_NOT_FOUND, 413 AUDIO_TOO_LARGE, 500 SYNC_FAILED
 */
export async function POST(
  request: NextRequest
): Promise<NextResponse<ApiResponse<SyncResponseResponse>>> {
  try {
    const formData = await request.formData();
    const input = await parseSyncFormData(formData);
    const result = await submitResponse(runInTransaction, input);

    console.log(
      `Sync ${result.outcome}: response ${result.responseId} for question ${input.questionId} ` +
        `(audio ${result.audio.stored ? `${result.audio.bytes} bytes` : 'none'})`
    );

    return NextResponse.json(
      { success: true, data: result },
      { status: result.outcome === 'created' ? 201 : 200 }
    );
  } catch (error) {
    if (error instanceof SubmissionError) {
      return NextResponse.json(
        { success: false, error: { code: error.code, message: error.message } },
        { status: error.status }
      );
    }

    console.error('Error syncing response:', error);

    return NextResponse.json(
      {
        success: false,
        error: {
          code: 'SYNC_FAILED',
          message: error instanceof Error ? error.message : 'Failed to sync response',
        },
      },
      { status: 500 }
    );
  }
}

/**
 * GET /api/responses/sync?sessionId=xxx
 * Get all responses for a session
 */
export async function GET(request: NextRequest): Promise<NextResponse> {
  try {
    const sessionId = request.nextUrl.searchParams.get('sessionId');

    if (!sessionId) {
      return NextResponse.json(
        {
          success: false,
          error: {
            code: 'MISSING_SESSION_ID',
            message: 'Session ID is required',
          },
        },
        { status: 400 }
      );
    }

    // Fetch responses from database
    const responses = await prisma.questionResponse.findMany({
      where: { sessionId },
      include: {
        question: {
          select: {
            questionNumber: true,
            question: true,
            category: true,
          },
        },
        evaluation: true,
      },
      orderBy: {
        question: {
          questionNumber: 'asc',
        },
      },
    });

    return NextResponse.json({
      success: true,
      data: {
        responses: responses.map((r) => ({
          id: r.id,
          questionId: r.questionId,
          sessionId: r.sessionId,
          questionNumber: r.question.questionNumber,
          questionText: r.question.question,
          category: r.question.category,
          transcription: r.transcription,
          durationSeconds: r.durationSeconds,
          audioUrl: r.audioUrl,
          status: r.status,
          startedAt: r.startedAt?.toISOString(),
          completedAt: r.completedAt?.toISOString(),
          hasEvaluation: r.evaluation !== null,
        })),
        count: responses.length,
      },
    });
  } catch (error) {
    console.error('Error getting responses:', error);

    return NextResponse.json(
      {
        success: false,
        error: {
          code: 'INTERNAL_ERROR',
          message: 'Failed to get responses',
        },
      },
      { status: 500 }
    );
  }
}
